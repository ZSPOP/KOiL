    /**
     * 取 [date]（"yyyy-MM-dd" 或 "yyyy-MM"）所属月份的汇率。
     *
     * 查不到当月时回退到最近一个更早的月份（表未及时更新）；早于全表则取最早月，
     * 保证任何输入都返回一个可用值，绝不返回 0 或 NaN——否则金额会被静默算成 0。
     */
    fun rateFor(date: String): Double {
        val month = date.take(7)
        RATES[month]?.let { return it }
        val earlier = RATES.keys.filter { it <= month }.maxOrNull()
        if (earlier != null) return RATES.getValue(earlier)
        return RATES.entries.minByOrNull { it.key }!!.value
    }
}
