package com.llpop.koil.data.oil

/**
 * 美元兑人民币月度均值表（USD/CNY，ECB 参考汇率，取月内工作日均值）。
 *
 * 【为什么是月度静态表，不接实时汇率】
 * 1. 汇率在月内的波动对最终幅度的影响 < 1%（见 docs/KOiL油价数据库机制.md 第 10 节），不值得为此新增一个
 *    网络依赖、缓存与断网降级链；
 * 2. 静态表断网可用、结果可复现，回测与线上算的是同一套数；
 * 3. 表随发版更新即可，成本远低于维护一个汇率源的可用性。
 *
 * 【为什么必须带汇率】
 * 旧实现的固定系数 56.5 元/吨/1% 其实是（布伦特 108 美元、汇率 7.14）那天的快照：
 * `56.5 = 0.01 × 7.33(桶/吨) × 7.14(CNY/USD) × 108(USD/bbl)`。
 * 把汇率与油价一起冻在快照里，油价中枢或汇率一漂移就会失真——实测 30 个窗口里隐含系数在 23.4~69.5 之间漂，
 * 固定 56.5 与单位换算口径差均值 74.9、最大 362.4 元/吨。故改为显式 `ΔP(USD/bbl) × 7.33 × FX`。
 *
 * 【维护】新增月份时按 `"yyyy-MM" to 月内均值` 追加；查不到时自动回退到最近一个更早的月份，
 * 因此漏更几个月只会带来很小的偏差，不会崩溃或显示假值。
 */
internal object UsdCnyMonthly {

